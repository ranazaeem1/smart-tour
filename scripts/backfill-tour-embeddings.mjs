import fs from "node:fs";
import path from "node:path";
import { GoogleGenerativeAI } from "@google/generative-ai";
import { createClient } from "@supabase/supabase-js";

const ROOT = process.cwd();
const ENV_PATH = path.join(ROOT, ".env.local");
const OUTPUT_PATH = path.join(ROOT, "supabase", "generated_tour_embeddings.sql");
const EMBEDDING_MODEL = process.env.GEMINI_EMBEDDING_MODEL || "gemini-embedding-001";
const EMBEDDING_DIMENSIONS = 768;

function loadLocalEnv() {
  if (!fs.existsSync(ENV_PATH)) return;

  const content = fs.readFileSync(ENV_PATH, "utf8");
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const index = line.indexOf("=");
    if (index === -1) continue;

    const key = line.slice(0, index).trim();
    const value = line.slice(index + 1).trim();
    if (!process.env[key]) process.env[key] = value;
  }
}

function requireEnv(name) {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is missing`);
  return value;
}

function sqlString(value) {
  return String(value).replaceAll("'", "''");
}

function vectorLiteral(values) {
  return `[${values.map((value) => Number(value).toFixed(8)).join(",")}]`;
}

function tourEmbeddingText(tour) {
  return [
    `Title: ${tour.title}`,
    `Destination: ${tour.destination}`,
    `Region: ${tour.region}`,
    `Category: ${tour.category}`,
    `Difficulty: ${tour.difficulty}`,
    `Duration: ${tour.duration} days`,
    `Price: PKR ${tour.price}`,
    `Safety score: ${tour.safety_score}`,
    Array.isArray(tour.tags) && tour.tags.length ? `Tags: ${tour.tags.join(", ")}` : "",
    Array.isArray(tour.highlights) && tour.highlights.length ? `Highlights: ${tour.highlights.join(", ")}` : "",
    Array.isArray(tour.included) && tour.included.length ? `Included: ${tour.included.join(", ")}` : "",
    "Pakistan tourism package semantic profile for matching terrain, climate, travel style, budget, safety, and activities.",
  ]
    .filter(Boolean)
    .join("\n");
}

async function embedText(model, text) {
  const result = await model.embedContent({
    content: { role: "user", parts: [{ text }] },
    outputDimensionality: EMBEDDING_DIMENSIONS,
  });

  const values = result.embedding?.values;
  if (!Array.isArray(values) || values.length !== EMBEDDING_DIMENSIONS) {
    throw new Error(`Invalid embedding dimension: ${values?.length || 0}`);
  }

  return values;
}

async function main() {
  loadLocalEnv();

  const supabaseUrl = requireEnv("NEXT_PUBLIC_SUPABASE_URL");
  const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY || requireEnv("NEXT_PUBLIC_SUPABASE_ANON_KEY");
  const hasServiceRole = Boolean(process.env.SUPABASE_SERVICE_ROLE_KEY);
  const geminiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_GEMINI_API_KEY;
  if (!geminiKey) throw new Error("GEMINI_API_KEY or GOOGLE_GEMINI_API_KEY is missing");

  const supabase = createClient(supabaseUrl, supabaseKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const model = new GoogleGenerativeAI(geminiKey).getGenerativeModel({ model: EMBEDDING_MODEL });

  const { data: tours, error } = await supabase
    .from("tours")
    .select("id,title,destination,region,price,duration,category,tags,max_group,difficulty,highlights,included,safety_score,available,embedding")
    .eq("available", true)
    .order("created_at", { ascending: false });

  if (error) throw new Error(`Failed to fetch tours: ${error.message}`);

  const targetTours = (tours || []).filter((tour) => !tour.embedding);
  if (!targetTours.length) {
    console.log(JSON.stringify({ ok: true, mode: hasServiceRole ? "database" : "sql", updated: 0, message: "No tours need embeddings." }));
    return;
  }

  const updates = [];

  for (const [index, tour] of targetTours.entries()) {
    const embedding = await embedText(model, tourEmbeddingText(tour));

    if (hasServiceRole) {
      const { error: updateError } = await supabase
        .from("tours")
        .update({ embedding })
        .eq("id", tour.id);

      if (updateError) throw new Error(`Failed to update ${tour.id}: ${updateError.message}`);
    } else {
      updates.push(
        `update public.tours\nset embedding = '${vectorLiteral(embedding)}'::vector\nwhere id = '${sqlString(tour.id)}';`
      );
    }

    console.log(JSON.stringify({ embedded: index + 1, total: targetTours.length, tour: tour.title }));
  }

  if (!hasServiceRole) {
    fs.writeFileSync(
      OUTPUT_PATH,
      [
        "-- Generated by scripts/backfill-tour-embeddings.mjs",
        "-- Run this in Supabase SQL Editor after 007_tour_semantic_search_pgvector.sql.",
        "begin;",
        ...updates,
        "commit;",
        "",
      ].join("\n\n"),
      "utf8"
    );
  }

  console.log(JSON.stringify({
    ok: true,
    mode: hasServiceRole ? "database" : "sql",
    updated: targetTours.length,
    output: hasServiceRole ? null : OUTPUT_PATH,
  }));
}

main().catch((error) => {
  console.error(JSON.stringify({ ok: false, error: error.message }));
  process.exit(1);
});
